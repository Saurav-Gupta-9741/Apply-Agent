/** What the model read in a question. */
export interface Meaning {
  intent: string;
  confidence: number;
}

/** Act on the model's reading from this confidence (98.6% right on real questions it had never seen). */
export const ACT_CONFIDENCE = 0.85;
/** Pure identity facts (name, email, phone): the question's own words must still say so (see EVIDENCE). Links are not
 * here: a link box can ask for many links, and the wrong one is a wrong value. */
/* calibration:start (generated by scripts/calibrate-intents.mjs from reports/oof.json; do not edit by hand) */
export const CALIBRATED_THRESHOLDS: Readonly<Record<string, number>> = {"currentCompany":0.7,"disability":0.92,"gender":0.7,"heard_about":0.7,"language_proficiency":0.7,"legal_declaration":0.79,"location":0.89,"notice_period":0.88,"onsite":0.73,"open_question":0.95,"other":0.95,"other_links":0.95,"other_person":0.7,"pronouns":0.7,"race":0.7,"salary_expected":0.7,"sexual_orientation":0.7,"skills_experience":0.92,"sponsorship":0.95,"work_authorization":0.95};
/* calibration:end */
export const SAFE_ACT_CONFIDENCE = 0.80;
export const SAFE_PROFILE_INTENTS = new Set<string>([
  "firstName", "lastName", "fullName", "email", "phone",
]);

/** Required confidence to act on a model reading. */
export function actThreshold(intent: string): number {
  if (SAFE_PROFILE_INTENTS.has(intent)) return Math.min(SAFE_ACT_CONFIDENCE, CALIBRATED_THRESHOLDS[intent] ?? SAFE_ACT_CONFIDENCE);
  return CALIBRATED_THRESHOLDS[intent] ?? ACT_CONFIDENCE;
}

