/** "Years of experience WITH React": a number of years about one skill is not the profile's total. */
const SPECIFIC_EXPERIENCE = /\b(with|in|using|on|of)\s+(?!(total|overall|professional|work|relevant work|industry|the industry|full time|paid)\b)\w/;

/** The question says something of the model's reading in plain words. */
function hasEvidence(label: string, intent: string): boolean {
  const text = normalize(label);
  const words = EVIDENCE[intent];
  if (!words || !words.test(text)) return false;
  if (intent === "experienceYears" && SPECIFIC_EXPERIENCE.test(text.replace(/\byears? of (professional |work )?experience\b/, ""))) return false;
  return true;
}

/** Yes/No choices: never a place for a name, a company or a link. */
function yesNoChoices(field: FieldDescriptor): boolean {
  const real = field.options.map((o) => normalize(o)).filter((o) => o && !/^(select|choose|please select|none|n a)\b/.test(o));
  return real.length > 0 && real.every((o) => /^(yes|no|y|n|true|false|maybe|prefer not|decline|i don t know)\b/.test(o));
}

/** The meaning a rule decision acted on, to compare with the model's reading. */
function actedMeaning(d: Decision): string | undefined {
  // The model names some meanings in snake case ("postal_code" for the profile's postalCode).
  if (d.kind === "profile") return ({ postalCode: "postal_code", educationLevel: "education_level", addressLine1: "address", addressLine2: "address" } as Record<string, string>)[d.key] ?? d.key;
  if (d.kind === "resume") return "resume";
  return undefined;
}

/** A value for the model's reading, through the same safety checks the rules use. */
function fromMeaning(field: FieldDescriptor, profile: Profile, meaning: Meaning, page?: PageFacts): Decision | undefined {
  const { intent } = meaning;
  if (!hasEvidence(field.label, intent)) return undefined;
  if (PROFILE_INTENTS.has(intent)) {
    // Choices and tick boxes are never answered with profile text; neither are yes/no questions or questions the
    // guards reject.
    if (["radio", "checkbox", "checkbox_group", "file"].includes(field.control) || notAProfileFact(field)) return undefined;
    if (yesNoChoices(field) || YES_NO_QUESTION.test(normalize(field.label))) return undefined;
    const value = profileValue(profile, intent as ProfileKey | "fullName");
    if (value) return { kind: "profile", key: intent as ProfileKey | "fullName", value };
    return field.required ? { kind: "ask", reason: "missing_profile_value" } : undefined;
  }
  if (TOPIC_OF[intent]) return factDecision({ ...field, label: hispanicHint(field.label, intent) }, profile, TOPIC_OF[intent], page);
  if (intent === "heard_about") {
    const heard = profile.facts?.heardFrom.trim();
    return heard && field.control !== "textarea" && field.control !== "checkbox" ? { kind: "answer", value: heard, question: "Quick answers › how you heard" } : undefined;
  }
  if (intent === "resume" && field.control === "file") return profile.resume ? { kind: "resume" } : undefined;
  if (intent === "skills_experience") return skillsExperienceAnswer(field, profile);
  if (intent === "language_proficiency") return languageAnswer(field, profile);
  if (intent === "onsite") return workModeAnswer(field, profile);
  if (intent === "travel") return travelAnswer(field, profile.facts);
  if (intent === "previous_employee") return previousEmployerAnswer(field, profile, page);
  return undefined;
}

/** The Hispanic/Latino rule looks for those words; the model may have recognised the question without them. */
function hispanicHint(label: string, intent: string): string {
  return intent === "hispanic" && !/hispanic|latin/i.test(label) ? `${label} (Hispanic or Latino)` : label;
}

export type DetailOwner = "self" | "another_person" | "company" | "legal";

export const ANOTHER_PERSON_SECTION_PATTERNS = /\b(references?|emergency contacts?|referees?|supervisors?|managers?|parents?|guardians?|next of kin)\b/i;
export const ANOTHER_PERSON_LABEL_PATTERNS = /\b(emergency contacts?|referees?|(?:reporting|previous|current)?\s*(?:supervisor|manager)['']?s?\s*(?:name|email|phone|contact)|father['']?s?|mother['']?s?|parent['']?s?\s*(?:name|email|phone)|guardian['']?s?|spouse['']?s?|next of kin)\b/i;
export const LEGAL_PATTERNS = /\b(consents?|declarations?|agreements?|background checks?|signatures?|terms|privacy polic(y|ies)|attestations?|certif(y|ied)|acknowledg(e|ment)s?)\b/i;
export const COMPANY_PATTERNS = /\b(company address(es)?|employer address(es)?|company phones?|office address(es)?|headquarters)\b/i;

/** Two-step decision: first determine whose detail is being asked.
 * An "another_person" or "legal" result always asks the candidate. */
export function whoseDetail(field: FieldDescriptor, meaning?: Meaning): DetailOwner {
  const normLabel = normalize(field.label);
  const normSection = field.section ? normalize(field.section) : "";

  const isModelConfident = Boolean(meaning && meaning.confidence >= actThreshold(meaning.intent));

  if (ANOTHER_PERSON_SECTION_PATTERNS.test(normSection) || ANOTHER_PERSON_LABEL_PATTERNS.test(normLabel) ||
      (isModelConfident && (meaning?.intent === "references" || meaning?.intent === "father_name"))) {
    return "another_person";
  }
  if (LEGAL_PATTERNS.test(normSection) || LEGAL_PATTERNS.test(normLabel) ||
      (isModelConfident && (meaning?.intent === "consent" || meaning?.intent === "legal_declaration"))) {
    return "legal";
  }
  if (COMPANY_PATTERNS.test(normSection) || COMPANY_PATTERNS.test(normLabel)) {
    return "company";
  }
  return "self";
}

/** Form context input: label + section heading + help text + nearest neighbour joined with [SEP] */
export function contextInput(field: FieldDescriptor, nearestLabel?: string, helpText?: string): string {
  const parts = [field.label];
  if (field.section) parts.push(`Section: ${field.section}`);
  if (helpText) parts.push(`Help: ${helpText}`);
  if (nearestLabel) parts.push(`Near: ${nearestLabel}`);
  return parts.join(" [SEP] ");
}

