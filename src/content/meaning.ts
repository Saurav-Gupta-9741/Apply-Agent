/** A value for a list must be one of its options: a saved fact the list does not offer ("India" for "Which country in
 * the United Kingdom…", "Pune" for "Location Cost Tier: High / Mid / Low") is asked, never forced in. */
function offeredBy(field: FieldDescriptor, value: string): boolean {
  if (!field.options.length || !["select", "radio", "dropdown", "combobox"].includes(field.control)) return true;
  return !!(yesNoOption(field.options, value) ?? bestOption(field.options, value)
    ?? field.options.find((o) => normalize(o) === normalize(value)));
}

/** The last check on every decision, whoever made it (rules, fact sheet, the question model). */
function safeToFill(field: FieldDescriptor, d: Decision, profile: Profile): boolean {
  if (d.kind !== "profile" && d.kind !== "answer" && d.kind !== "work") return true;
  // "What degree are you currently pursuing?" asks a student; someone who has finished is asked.
  if (d.kind === "profile" && /^(degree|educationLevel|school|discipline|graduationYear)$/.test(d.key)
    && /\b(currently pursuing|pursuing|enrolled|working towards|in progress)\b/i.test(field.label) && profile.educationStatus !== "pursuing") return false;
  if (ONLY_SOME.test(field.label.trim()) && (d.kind === "profile" || d.kind === "work" || MODEL_DECISIONS.has(d))) return false;
  if (NOT_THIS_FACT.some(([applies, words]) => applies(d) && words.test(field.label))) return false;
  return offeredBy(field, d.value);
}

const UK_NATIONS = /^(england|scotland|wales|northern ireland)$/i;
const OUTSIDE = /^(?:not in|not living in|not based in|outside(?: of)?|i (?:do not|don't|dont) (?:live|reside) in|i (?:live|reside|am based) outside(?: of)?|i am not (?:located|based|living) in|none of the above,? i (?:live|reside) outside(?: of)?|n\/?a\s*[-–(]?\s*(?:i )?(?:live|reside|am based) outside(?: of)?)\s+(?:the\s+)?(.+?)\)?\.?$/i;

/** "Select your state of residence. Select 'Not in the US' if you reside outside the United States": the option for
 * people outside a country, when the Profile's country is clearly another one ("Not in England" for someone in India;
 * someone in the UK may live in England, so they are asked). */
function outsideOption(field: FieldDescriptor, profile: Profile): string | undefined {
  if (!field.options.length || !/\b(resid\w*|live|living|located|based|where)\b/i.test(field.label)) return undefined;
  const home = profile.country?.trim() ? countryCode(profile.country) : undefined;
  if (!home) return undefined;
  const hits = field.options.filter((o) => {
    const place = OUTSIDE.exec(o.trim())?.[1]?.trim();
    if (!place) return false;
    const iso = UK_NATIONS.test(place) ? "GB" : countryCode(place.replace(/^(?:the )/i, ""));
    return !!iso && iso !== home;
  });
  return hits.length === 1 ? hits[0] : undefined;
}

export function decideWithMeaning(field: FieldDescriptor, profile: Profile, answers: Parameters<typeof decide>[2], page?: PageFacts,
  meaning?: Meaning): Decision {
  const decided = decideWithMeaningInner(field, profile, answers, page, meaning);
  const safe = safeToFill(field, decided, profile);
  const outside = (!safe || decided.kind === "ask" || decided.kind === "skip") ? outsideOption(field, profile) : undefined;
  const d: Decision = outside ? { kind: "answer", value: outside, question: "Quick answers › where you live", source: `from your Profile country (${profile.country})` }
    : safe ? decided
    : field.required ? { kind: "ask", reason: "unknown" } : { kind: "skip", reason: "not sure this saved answer fits: left for you" };
  if (!field.machineTranslated) return d;
  if (d.kind === "ask" || d.kind === "skip" || d.kind === "draft") return d;
  if (d.kind === "profile" && MACHINE_TRANSLATION_SAFE_KEYS.has(d.key)) return d;
  return field.required ? { kind: "ask", reason: "unknown" } : { kind: "skip", reason: "machine-translated question: answered by you" };
}

function decideWithMeaningInner(field: FieldDescriptor, profile: Profile, answers: Parameters<typeof decide>[2], page?: PageFacts,
  meaning?: Meaning): Decision {
  const rule = decide(field, profile, answers, page);

  // Two-step decision: if section or question context indicates another person,
  // NEVER fill the candidate's own personal identity facts (name, email, phone).
  const owner = whoseDetail(field, meaning);
  if (owner === "another_person" && rule.kind === "profile" &&
      (rule.key === "firstName" || rule.key === "lastName" || rule.key === "fullName" || rule.key === "email" || rule.key === "phone")) {
    return field.required ? { kind: "ask", reason: "unknown" } : { kind: "skip", reason: "another person: entered by you only" };
  }
  if (owner === "legal" && (rule.kind === "profile" || (rule.kind === "answer" && (rule.reused || rule.question.startsWith("Quick answers › "))))) {
    return field.required ? { kind: "ask", reason: "sensitive" } : { kind: "skip", reason: "legal: entered by you only" };
  }

  // The fact sheet: wordings the rules do not name ("Who is your current or previous employer?", "Branch", "Have you
  // worked with Kafka?"), answered only from the user's own saved data and marked for a quick check. Never for a
  // question the model is very sure is someone else's, a consent or an open question.
  const rulesGaveUp = rule.kind === "ask" && rule.reason !== "sensitive" || rule.kind === "skip" && /in profile|optional choice/.test(rule.reason);
  const modelObjects = !!meaning && meaning.confidence >= DOUBT_CONFIDENCE && NEVER_FROM_PROFILE.has(meaning.intent);
  if (rulesGaveUp && owner === "self" && !modelObjects) {
    const fact = factSheetAnswer(field.translatedLabel ? { ...field, label: field.translatedLabel } : field, profile, undefined, page);
    if (fact) {
      MODEL_DECISIONS.add(fact);
      return fact;
    }
  }

  if (!meaning) return rule;

  // Doubt: the rules would fill a profile fact, but the model is very sure the question is about something else
  // ("Preferred Last Name" read as a first name, someone else's details, a consent…). Asking is the safe side.
  const acted = actedMeaning(rule);
  // The model reads English: it may doubt the rules only on English questions ("Prénom" is not "other").
  if (acted && meaning.confidence >= DOUBT_CONFIDENCE && readsAsEnglish(field.label) && meaning.intent !== acted && !sameFamily(acted, meaning.intent)) {
    return field.required ? { kind: "ask", reason: "unknown" } : { kind: "skip", reason: `unsure: reads like ${meaning.intent.replace(/_/g, " ")}` };
  }

  // Gaps: the rules did not know the question; the model does, confidently.
  // The form's own words decided ("Non-U.S. candidates enter 00000", "Which U.S. State…?" for a user in India): the
  // model's reading of the same question cannot overrule them.
  if (nonUsInstruction(field, profile) || foreignSubdivision(field, profile)) return rule;
  const ruleGaveUp = rule.kind === "ask" && rule.reason !== "sensitive" || rule.kind === "skip" && /not in profile|optional choice/.test(rule.reason)
    || rule.kind === "ask" && rule.reason === "sensitive" && !rule.topic;
  const sensitiveGap = rule.kind === "ask" && rule.reason === "sensitive" && rule.topic && TOPIC_OF[meaning.intent] === rule.topic;
  if ((ruleGaveUp || sensitiveGap) && meaning.confidence >= actThreshold(meaning.intent) && !NEVER_FROM_PROFILE.has(meaning.intent)) {
    const decision = fromMeaning(field, profile, meaning, page);
    if (decision) {
      MODEL_DECISIONS.add(decision);
      return decision;
    }
  }
  return rule;
}

const ENGLISH = /\b(the|your|you|what|which|where|when|how|please|name|of|to|in|for|are|is|do|a|an|and|or|with|link|url|number|address|email|phone|profile|preferred|current|last|first|full|website|portfolio|company|title|city|country)\b/;

function readsAsEnglish(label: string): boolean {
  return ENGLISH.test(normalize(label));
}

/** Readings close enough not to doubt each other (a full name where the rules saw a first name, a city vs country…). */
function sameFamily(a: string, b: string): boolean {
  const families = [["firstName", "fullName", "lastName"], ["location", "country", "state", "address"], ["linkedin", "github", "portfolio", "other_links", "resumeUrl", "resume"],
    ["degree", "education_level", "discipline"], ["currentTitle", "currentCompany"]];
  return families.some((f) => f.includes(a) && f.includes(b)) && !(a === "firstName" && b === "lastName") && !(a === "lastName" && b === "firstName");
}
