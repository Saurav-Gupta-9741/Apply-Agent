// Per-meaning act thresholds, measured on the model's out-of-fold readings (reports/oof.json: real questions the model
// never saw in training).
//   node scripts/calibrate-intents.mjs          write reports/calibration.json and the thresholds block in src/content/meaning.ts
//   node scripts/calibrate-intents.mjs --check  exit 1 when meaning.ts is out of date with reports/oof.json
// Rule, per meaning the model can read: the lowest threshold (in steps of 0.01, never below FLOOR) at which the
// model's readings of that meaning are right at least 98% of the time on at least 15 questions. Without one, the
// default 0.85 stays. Meanings that are never filled from a reading ("other", "open_question") and links (a link box
// can ask for many links) are never lowered. A calibrated threshold above the default is kept: stricter is safer.
// The threshold is only one of the two keys: the question's own words (EVIDENCE in meaning.ts) and every safety check
// for that kind of answer still apply.
import { readFileSync, writeFileSync } from "node:fs";

const DEFAULT = 0.85;
const PRECISION = 0.98;
const MIN_ACTS = 15;
/** Below this, 15 right answers are too few to trust a reading (the 0.70-0.85 band is 82% right overall). */
const FLOOR = 0.7;
/** Never lowered below this. */
const NEVER_LOWER = { other: 0.95, open_question: 0.95, linkedin: DEFAULT, github: DEFAULT, portfolio: DEFAULT, resumeUrl: DEFAULT, other_links: 0.95 };

const oof = JSON.parse(readFileSync("reports/oof.json", "utf8"));
const intents = [...new Set(oof.map((o) => o.guess))].sort();
const thresholds = {};
const detail = {};
for (const intent of intents) {
  const read = oof.filter((o) => o.guess === intent);
  let found;
  for (let k = Math.round(FLOOR * 100); k <= 99; k++) {
    const t = k / 100;
    const acts = read.filter((o) => o.confidence >= t);
    const right = acts.filter((o) => o.truth === intent).length;
    if (acts.length >= MIN_ACTS && right / acts.length >= PRECISION) {
      found = { threshold: t, acts: acts.length, right };
      break;
    }
  }
  let threshold = found ? found.threshold : DEFAULT;
  if (NEVER_LOWER[intent] !== undefined) threshold = Math.max(threshold, NEVER_LOWER[intent]);
  const acts = read.filter((o) => o.confidence >= threshold);
  const right = acts.filter((o) => o.truth === intent).length;
  detail[intent] = { threshold, calibrated: !!found, acts: acts.length, right, precision: acts.length ? Number((right / acts.length).toFixed(4)) : null };
  if (threshold !== DEFAULT) thresholds[intent] = threshold;
}

const report = {
  source: "reports/oof.json",
  questions: oof.length,
  rule: { precision: PRECISION, minActs: MIN_ACTS, floor: FLOOR, default: DEFAULT, neverLower: NEVER_LOWER },
  thresholds,
  detail,
};

const block = `/* calibration:start (generated by scripts/calibrate-intents.mjs from reports/oof.json; do not edit by hand) */\n`
  + `export const CALIBRATED_THRESHOLDS: Readonly<Record<string, number>> = ${JSON.stringify(thresholds)};\n`
  + `/* calibration:end */`;
const meaningPath = "src/content/meaning.ts";
const meaning = readFileSync(meaningPath, "utf8");
const re = /\/\* calibration:start[\s\S]*?\/\* calibration:end \*\//;
if (!re.test(meaning)) throw new Error("meaning.ts has no calibration block");
const updated = meaning.replace(re, block);

if (process.argv.includes("--check")) {
  if (updated !== meaning) {
    console.error("src/content/meaning.ts thresholds are out of date: run node scripts/calibrate-intents.mjs");
    process.exit(1);
  }
  console.log("calibration up to date");
} else {
  writeFileSync("reports/calibration.json", JSON.stringify(report, null, 2) + "\n");
  writeFileSync(meaningPath, updated);
  console.log("Per-meaning thresholds (changed from the default only):");
  for (const [k, v] of Object.entries(thresholds)) console.log(`  ${k.padEnd(22)} ${v.toFixed(2)}  ${detail[k].right}/${detail[k].acts} right`);
}
